import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { ART_SLOTS, DECOR_KINDS } from "@/lib/themes/decor";
import { SRC, read, sourceFiles, stripComments } from "./themes-decor-helpers";

/**
 * ORNAMENT AND PICTURES ARE DRAWN IN FOUR PLACES, AND NOWHERE ELSE.
 *
 * The owner's rule, kept from the OMS: «ولا رسمة ورا رقم أو مبلغ» — nothing is drawn behind a number, an amount
 * or a table. A glow under a column of figures is a glow somebody reads through, every row, all day. So the layer
 * is `<ThemeDecor kind="…">` with exactly four kinds, each used by one family of files, and this file sweeps
 * the source for a fifth place. The sweep is a list of what is ALLOWED, not of what is forbidden: a new file that
 * draws a layer fails here until somebody decides, on purpose, that it may.
 */

const files = sourceFiles();
const text = (rel: string): string => readFileSync(path.join(SRC, rel), "utf8");

interface Caller {
  file: string;
  kind: string;
}
const callers: Caller[] = files.flatMap((file) =>
  [...stripComments(text(file)).matchAll(/<ThemeDecor\s+kind="([^"]+)"/g)].map((m) => ({ file, kind: m[1] as string })),
);

/** Where each place may be drawn — pinned to the exact caller files, not to loose name patterns:
 *  a new file that wants a layer is a decision, made here on purpose. */
const ALLOWED_FILES: Record<(typeof DECOR_KINDS)[number], readonly string[]> = {
  door: ["components/theme/door-shell.tsx"],
  empty: ["components/ui/card.tsx"],
  sidebar: ["components/shell/sidebar.tsx"],
  strip: ["components/today/today-hero.tsx"],
};
const ALLOWED: Record<(typeof DECOR_KINDS)[number], (file: string) => boolean> = Object.fromEntries(
  Object.entries(ALLOWED_FILES).map(([k, fs]) => [k, (f: string) => (fs as readonly string[]).includes(f)]),
) as typeof ALLOWED;

describe("the layer is drawn in four places — the door, an empty list, the header, the Today strip", () => {
  it("— every use names its place as a literal, and the place is one of the four", () => {
    expect(callers.length).toBeGreaterThanOrEqual(2);
    for (const c of callers) expect(DECOR_KINDS as readonly string[], `${c.file}: kind="${c.kind}"`).toContain(c.kind);
    // a computed kind could not be swept
    for (const file of files.filter((f) => f !== "components/theme/theme-decor.tsx")) {
      expect(stripComments(text(file)), `${file}: a computed kind cannot be checked`).not.toMatch(/<ThemeDecor\s+kind=\{/);
    }
  });

  it("— each place is drawn only by its own family of files", () => {
    for (const c of callers) {
      const allowed = ALLOWED[c.kind as keyof typeof ALLOWED];
      expect(allowed(c.file), `${c.file} draws «${c.kind}» — a fifth place?`).toBe(true);
    }
  });

  it("— the door and an empty list are drawn today (the header and the strip arrive with the shell and the Today page)", () => {
    expect(callers.filter((c) => c.kind === "door").map((c) => c.file)).toEqual(["components/theme/door-shell.tsx"]);
    expect(callers.filter((c) => c.kind === "empty").map((c) => c.file)).toEqual(["components/ui/card.tsx"]);
  });

  it("— the class of the layer is written by one component and generated by one module, never typed by hand in a screen", () => {
    // (the cookie that stores the level is also called `zk-decor`: it is a name, not a class, and is not what is swept)
    const layerClass = /\bzk-decor-(?:door|empty|sidebar|strip|l|b)\b|(?:className|class)\s*=\s*\{?\s*["'`][^"'`]*\bzk-decor\b(?!-)/;
    const own = ["components/theme/theme-decor.tsx", "lib/themes/decor.ts"];
    const writers = files.filter((f) => !own.includes(f) && layerClass.test(stripComments(text(f))));
    expect(writers, "a screen that draws its own layer").toEqual([]);
    expect(layerClass.test(stripComments(text("components/theme/theme-decor.tsx")))).toBe(true);
  });

  it("— and the stylesheet comes with the component, not with the page everybody downloads", () => {
    expect(stripComments(text("components/theme/theme-decor.tsx"))).toContain('import "./decor.css"');
    for (const sheet of ["app/globals.css", "app/themes.css"]) {
      try {
        expect(read("src", ...sheet.split("/")), `${sheet} would ship every picture to everybody`).not.toContain("brand/decor");
      } catch {
        /* the theme stylesheet does not exist yet — nothing to check */
      }
    }
  });
});

describe("never behind a number, an amount, a quantity or a table", () => {
  /** The components that render money, quantities, dates against figures, or rows. */
  const MONEY = [/^components\/(crm-view|goals-view|production-view|calendar-grid|task-row|timeline-gantt)\.tsx$/, /^components\/analytics[^/]*\.tsx$/, /^app\/\(app\)\/analytics\//];
  const money = files.filter((f) => MONEY.some((re) => re.test(f)));

  it("— the money and quantity screens exist, so this sweep is not empty", () => {
    expect(money.length).toBeGreaterThanOrEqual(5);
    for (const name of ["components/crm-view.tsx", "components/goals-view.tsx", "components/production-view.tsx", "components/calendar-grid.tsx", "components/task-row.tsx", "components/timeline-gantt.tsx"]) {
      expect(files, name).toContain(name);
    }
  });

  it("— none of them imports ThemeDecor, ArtSlot or the layer's class", () => {
    const offenders: string[] = [];
    for (const f of money) {
      const code = stripComments(text(f));
      if (/ThemeDecor|theme-decor|ArtSlot|art-slot|zk-decor|zk-scrim/.test(code)) offenders.push(f);
    }
    expect(offenders, "a decoration on a screen of figures").toEqual([]);
  });

  it("— and no file that renders a table draws a layer", () => {
    const offenders = callers.map((c) => c.file).filter((f) => /<table\b|<Table\b/.test(stripComments(text(f))));
    expect(offenders).toEqual([]);
  });
});

describe("text over a picture is always on a panel — the door's three screens and the empty list keep to the tokens that are read against it", () => {
  const OWNED = ["components/theme/door-shell.tsx", "components/auth-form.tsx", "components/onboarding-form.tsx", "components/ui/card.tsx", "components/theme/art-slot.tsx", "components/theme/theme-decor.tsx", "components/theme/decor-visibility.tsx"];
  const DOOR = ["components/theme/door-shell.tsx", "components/auth-form.tsx", "components/onboarding-form.tsx"];

  it("— the door has no text in the dimmer `muted` colour (only fg, fg-muted and accent are held over a picture)", () => {
    for (const f of DOOR) expect(stripComments(text(f)), `${f} uses text-muted`).not.toMatch(/(^|[\s"'`:])text-muted\b/);
  });

  it("— no hard-coded colour in what the decoration owns: no palette class, no hex, no inline colour", () => {
    const palette = /\b(?:text|bg|border|ring|from|to|via|fill|stroke|divide|outline|shadow)-(?:red|green|emerald|amber|orange|yellow|sky|blue|cyan|indigo|violet|fuchsia|rose|teal|lime|purple|pink|slate|gray|zinc|neutral|stone|white|black)(?:-\d{2,3})?(?:\/\d+)?\b/;
    for (const f of OWNED) {
      const code = stripComments(text(f));
      expect(code, `${f}: palette class`).not.toMatch(palette);
      expect(code, `${f}: hex colour`).not.toMatch(/#[0-9a-fA-F]{3,8}\b/);
    }
  });

  it("— errors and confirmations use the meaning tokens (`danger`, `ok`)", () => {
    expect(stripComments(text("components/auth-form.tsx"))).toContain("text-danger");
    const onboarding = stripComments(text("components/onboarding-form.tsx"));
    expect(onboarding).toContain("text-danger");
    expect(onboarding).toContain("text-ok");
  });

  it("— the door uses the new mark and wordmark; the old English one (Logo: «Zakai.io / Intelligent Systems») is gone from it", () => {
    for (const f of DOOR) {
      const code = stripComments(text(f));
      expect(code, `${f} still imports the old wordmark`).not.toMatch(/import \{[^}]*\bLogo\b[^}]*\} from "@\/components\/logo"/);
      expect(code, `${f}: old name`).not.toMatch(/Zakai|Intelligent Systems/);
    }
    expect(stripComments(text("components/theme/door-shell.tsx"))).toMatch(/DolphinMark/);
    expect(stripComments(text("components/theme/door-shell.tsx"))).toContain('t("app.name")');
  });

  it("— right-to-left: the files of the decoration use logical properties, never left/right for layout", () => {
    for (const f of OWNED) {
      const code = stripComments(text(f));
      expect(code, `${f}: physical margin or padding`).not.toMatch(/(^|[\s"'`])-?(?:ml|mr|pl|pr)-(?:\d|\[|px|auto)/);
      expect(code, `${f}: left/right offset`).not.toMatch(/(^|[\s"'`])-?(?:left|right)-(?:\d|\[|px|full|1\/)/);
      expect(code, `${f}: text-left / text-right`).not.toMatch(/(^|[\s"'`])text-(?:left|right)\b/);
      expect(code, `${f}: rounded-l / rounded-r`).not.toMatch(/(^|[\s"'`])rounded-[lr]-/);
    }
  });
});

describe("the layer's callers are pinned by name", () => {
  it("— each kind names its exact caller files, and no regex broadens the list", () => {
    expect(ALLOWED_FILES.sidebar).toEqual(["components/shell/sidebar.tsx"]);
    expect(ALLOWED_FILES.strip).toEqual(["components/today/today-hero.tsx"]);
    expect(ALLOWED_FILES.door).toEqual(["components/theme/door-shell.tsx"]);
    expect(ALLOWED_FILES.empty).toEqual(["components/ui/card.tsx"]);
  });

  it("— and the pinned files are exactly the files that really draw the layers", () => {
    for (const [kind, fs] of Object.entries(ALLOWED_FILES)) {
      expect(
        callers.filter((c) => c.kind === kind).map((c) => c.file).sort(),
        `kind «${kind}»`,
      ).toEqual([...fs].sort());
    }
  });
});

describe("pictures are named, not typed twice: every slot a screen asks for is one of the agreed names", () => {
  it("— `<ArtSlot slot=\"…\">` and `art=\"…\"` in the source use the twelve names, and nothing else", () => {
    const asked: Array<{ file: string; slot: string }> = [];
    for (const file of files) {
      const code = stripComments(text(file));
      for (const m of code.matchAll(/<ArtSlot\s+[^>]*slot="([^"]+)"/g)) asked.push({ file, slot: m[1] as string });
      for (const m of code.matchAll(/\bart="([^"]+)"/g)) asked.push({ file, slot: m[1] as string });
    }
    expect(asked.length).toBeGreaterThanOrEqual(1);
    for (const a of asked) expect(ART_SLOTS as readonly string[], `${a.file}: «${a.slot}»`).toContain(a.slot);
  });

  it("— the door asks for the login-door picture, and only the door", () => {
    const door = files.filter((f) => /<ArtSlot\s+[^>]*slot="login-door"/.test(stripComments(text(f))));
    expect(door).toEqual(["components/theme/door-shell.tsx"]);
  });
});
